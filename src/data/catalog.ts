/**
 * Concrete ProductRepository implementation (Phase 1 Local JSON/TS Store)
 * Can be swapped for Shopify Storefront GraphQL API adapter in Phase 2
 */
export class LocalProductRepository implements ProductRepository {
  async getAllProducts(): Promise<Product[]> {
    return PRODUCTS;
  }

  async getProductBySlug(slug: string): Promise<Product | null> {
    return PRODUCTS.find((p) => p.slug === slug) || null;
  }

  async getProductsByCategory(category: string, subCollection?: string): Promise<Product[]> {
    return PRODUCTS.filter((p) => {
      const matchesCat = p.category === category || (category === "sale" && p.isClearance);
      if (!matchesCat) return false;
      if (subCollection) {
        return p.subCollection === subCollection || p.clearanceTier === subCollection;
      }
      return true;
    });
  }

  async getTrendingProducts(): Promise<Product[]> {
    return PRODUCTS.filter((p) => p.isTrending);
  }

  async getNewArrivals(): Promise<Product[]> {
    return PRODUCTS.filter((p) => p.isNewArrival);
  }

  async getSaleProducts(tier?: string): Promise<Product[]> {
    return PRODUCTS.filter((p) => {
      if (!p.isClearance && p.category !== "sale") return false;
      if (tier) return p.clearanceTier === tier;
      return true;
    });
  }

  async searchProducts(query: string, filters?: ProductFilterOptions): Promise<Product[]> {
    const q = query.toLowerCase().trim();
    return PRODUCTS.filter((product) => {
      const matchText =
        product.name.toLowerCase().includes(q) ||
        product.sku.toLowerCase().includes(q) ||
        product.description.toLowerCase().includes(q) ||
        product.tags.some((t) => t.toLowerCase().includes(q)) ||
        product.subCollection.toLowerCase().includes(q);

      if (q && !matchText) return false;
      if (filters?.category && product.category !== filters.category) return false;
      if (filters?.subCollection && product.subCollection !== filters.subCollection) return false;
      if (filters?.minPrice && product.price < filters.minPrice) return false;
      if (filters?.maxPrice && product.price > filters.maxPrice) return false;
      if (filters?.sizes && filters.sizes.length > 0) {
        if (!filters.sizes.some((s) => product.sizes.includes(s))) return false;
      }
      return true;
    });
  }
}

export const productRepository = new LocalProductRepository();
